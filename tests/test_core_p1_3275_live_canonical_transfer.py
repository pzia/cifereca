def prepare(tmp_path):
    service = _service(tmp_path)
    root = tmp_path / "EBooks"
    a = root / "alice" / "local" / "book.pdf"
    a.parent.mkdir(parents=True, exist_ok=True)
    a.write_bytes(BYTES)
    artifact = "sha256:" + SHA
    service.storage.artifact_put({
        "artifact_id": artifact, "sha256": SHA,
        "size": len(BYTES), "media_format": "pdf",
    })
    placement = _placement(
        service, a, artifact_id=artifact, identity_id="alice",
        source_item_id="book",
    )
    service.storage.catalog_entry_put({
        "artifact_id": artifact, "placement_id": placement,
        "title": "Synthetic book", "identity_id": "alice",
        "provider_id": "local", "item_id": "book",
        "local_state": "local", "media_format": "pdf",
        "metadata": {"path": str(a)},
    })
    return service, root, a, placement, artifact


def canon_rows(storage):
    with storage._lock, storage._connect() as db:
        return {
            table: db.execute("SELECT count(*) FROM " + table).fetchone()[0]
            for table in ("artifacts", "placements", "source_references",
                          "origin_links", "entitlements")
        }


def test_actual_send_publishes_one_copy_and_two_contextual_origins(tmp_path, monkeypatch):
    service, root, a, placement_a, artifact = prepare(tmp_path)
    lock = tmp_path / "global-acquisition.lock"
    monkeypatch.setattr("cifereca.paths.acquisition_lock_file", lambda: lock)
    monkeypatch.setattr("cifereca.core.canonical_transfer.acquisition_lock_file", lambda: lock)
    try:
        first = service.materialize_to_identity(placement_a, "bob")
        b = Path(first["path"])
        assert first["status"] == "complete"
        assert b.read_bytes() == a.read_bytes() == BYTES
        assert b != a and os.stat(a).st_ino != os.stat(b).st_ino
        assert service.storage.placement_get(first["placement_id"])["identity_id"] == "bob"
        assert canon_rows(service.storage) == {
            "artifacts": 1, "placements": 2,
            "source_references": 1, "origin_links": 2, "entitlements": 0,
        }
        with service.storage._lock, service.storage._connect() as db:
            assert db.execute(
                "SELECT origin_kind,identity_id,from_identity_id "
                "FROM origin_links ORDER BY origin_kind"
            ).fetchall() == [
                ("cifereca", "bob", None),
                ("transfer", "bob", "alice"),
            ]
            assert db.execute(
                "SELECT identity_id,reference_kind,synchronizable "
                "FROM source_references"
            ).fetchone() == ("bob", "internal", 0)
        second = service.materialize_to_identity(placement_a, "bob")
        assert second["status"] == "unchanged"
        assert second["path"] == first["path"]
        assert second["placement_id"] == first["placement_id"]
        assert canon_rows(service.storage) == {
            "artifacts": 1, "placements": 2,
            "source_references": 1, "origin_links": 2, "entitlements": 0,
        }
        assert service.storage.placement_get(
            first["placement_id"]
        )["metadata"]["file_origin_identity_id"] == "alice"
    finally:
        service.close()


def test_actual_send_sql_origin_failure_never_commits_a_forged_b_placement(
    tmp_path, monkeypatch,
):
    service, root, a, placement_a, artifact = prepare(tmp_path)
    lock = tmp_path / "global-acquisition.lock"
    monkeypatch.setattr("cifereca.paths.acquisition_lock_file", lambda: lock)
    monkeypatch.setattr("cifereca.core.canonical_transfer.acquisition_lock_file", lambda: lock)
    before = canon_rows(service.storage)
    with service.storage._lock, service.storage._connect() as db:
        db.execute(
            "CREATE TRIGGER test_canonical_send_rollback BEFORE INSERT ON "
            "origin_links WHEN NEW.origin_kind='cifereca' "
            "BEGIN SELECT RAISE(ABORT,'synthetic_origin_write_failure'); END"
        )
    try:
        with pytest.raises(sqlite3.IntegrityError, match="synthetic_origin_write_failure"):
            service.materialize_to_identity(placement_a, "bob")
        assert canon_rows(service.storage) == before
        assert service.storage.entitlements() == []
        assert a.read_bytes() == BYTES
        # A file created during a failed transaction remains physically
        # untouched; it is NOT a published recipient placement nor a right.
        assert (root / "bob" / "local" / "book.pdf").read_bytes() == BYTES
    finally:
        with service.storage._lock, service.storage._connect() as db:
            db.execute("DROP TRIGGER test_canonical_send_rollback")
        service.close()


def test_legacy_noncanonical_file_still_sends_without_inventing_origins(tmp_path):
    service = _service(tmp_path)
    root = tmp_path / "EBooks"
    a = root / "alice" / "local" / "legacy.epub"
    a.parent.mkdir(parents=True, exist_ok=True)
    a.write_bytes(b"legacy-non-epub-bytes")
    old = _placement(service, a, artifact_id="sha256:legacy")
    try:
        result = service.materialize_to_identity(old, "bob")
        assert Path(result["path"]).read_bytes() == a.read_bytes()
        assert canon_rows(service.storage)["origin_links"] == 0
        assert canon_rows(service.storage)["source_references"] == 0
        assert result["status"] == "complete"
        assert service.materialize_to_identity(old, "bob")["status"] == "unchanged"
    finally:
        service.close()


def test_altered_source_artifact_hash_never_mints_transfer_origin(tmp_path):
    service, root, a, placement_a, artifact = prepare(tmp_path)
    a.write_bytes(b"%PDF-1.7\nAn unrelated changed file\n")
    try:
        with pytest.raises(
            Exception, match="Artifact source modifié depuis son indexation",
        ):
            service.materialize_to_identity(placement_a, "bob")
        assert canon_rows(service.storage)["origin_links"] == 0
        assert canon_rows(service.storage)["placements"] == 1
        assert service.storage.entitlements() == []
        assert not (root / "bob" / "local" / "book.pdf").exists()
    finally:
        service.close()


@pytest.mark.parametrize("failure_at", ["placement", "catalog"])
@pytest.mark.parametrize("source_projection", ["complete", "missing"])
def test_retry_after_canonical_commit_repairs_projection_without_second_copy(
    tmp_path, monkeypatch, failure_at, source_projection,
):
    service, root, a, placement_a, artifact = prepare(tmp_path)
    if source_projection == "missing":
        with service.storage._lock, service.storage._connect() as db:
            db.execute("UPDATE placements SET provider_id=NULL,source_item_id=NULL "
                       "WHERE placement_id=?", (placement_a,))
    lock = tmp_path / "global-acquisition.lock"
    monkeypatch.setattr("cifereca.paths.acquisition_lock_file", lambda: lock)
    monkeypatch.setattr("cifereca.core.canonical_transfer.acquisition_lock_file", lambda: lock)
    method = "placement_put" if failure_at == "placement" else "catalog_entry_put"
    original = getattr(service.storage, method)
    armed = True

    def fail_projection(row, *args, **kwargs):
        nonlocal armed
        if armed and row.get("identity_id") == "bob":
            armed = False
            raise RuntimeError("synthetic_projection_interruption")
        return original(row, *args, **kwargs)

    monkeypatch.setattr(service.storage, method, fail_projection)
    try:
        with pytest.raises(RuntimeError, match="synthetic_projection_interruption"):
            service.materialize_to_identity(placement_a, "bob")
        assert canon_rows(service.storage)["origin_links"] == 2
        b = root / "bob" / ("shared" if source_projection == "missing" else "local") / "book.pdf"
        inode = b.stat().st_ino
        retry = service.materialize_to_identity(placement_a, "bob")
        assert Path(retry["path"]) == b
        assert b.stat().st_ino == inode
        assert list(b.parent.iterdir()) == [b]
        assert canon_rows(service.storage)["placements"] == 2
        assert canon_rows(service.storage)["origin_links"] == 2
        entries = [e for e in service.storage.catalog_entries()
                   if e.get("identity_id") == "bob"]
        assert len(entries) == 1
        assert entries[0]["placement_id"] == retry["placement_id"]
        assert service.materialize_to_identity(placement_a, "bob")["status"] == "unchanged"
        assert service.storage.entitlements() == []
        assert a.read_bytes() == b.read_bytes() == BYTES
    finally:
        service.close()


def _send_from_controller(service, placement_id, target):
    """Actual action callback + worker + LibraryService; widgets are test doubles."""
    from cifereca.gui.local_book_action_controller import add_local_book_actions
    from tests.test_core_ui_1129_local_book_actions import _environment

