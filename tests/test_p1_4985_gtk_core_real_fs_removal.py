def test_gtk_cancel_then_confirm_unlinks_only_the_real_managed_usb_copy(
    gtk_core,
):
    ctx = gtk_core
    rig = ctx.rig
    source = rig.source.read_bytes()
    assert rig.final.read_bytes() == source
    assert rig.journal.get(rig.consent.operation_id) is None
    ctx.button.callbacks["clicked"](ctx.button)
    assert not ctx.host.runner.history[1:]
    assert ctx.host.runner.jobs
    assert ctx.dialogs == []
    assert rig.final.read_bytes() == source

    # Real Core disk scan and durable managed-receipt attribution run only
    # inside the first explicit worker, not while rendering/clicking.
    ctx.host.runner.advance()
    assert len(ctx.dialogs) == 1 and ctx.dialogs[0].presented
    assert rig.final.read_bytes() == source
    ctx.dialogs[0].answer("cancel")
    assert ctx.host.runner.jobs == []
    assert rig.final.read_bytes() == source
    assert rig.journal.get(rig.consent.operation_id) is None

    # A second explicit click opens a *new* destructive confirmation.
    ctx.button.callbacks["clicked"](ctx.button)
    ctx.host.runner.advance()
    assert len(ctx.dialogs) == 2
    assert ctx.dialogs[1].presented
    ctx.dialogs[1].answer("delete")
    assert len(ctx.host.runner.jobs) == 1
    assert rig.final.read_bytes() == source

    # The second worker invokes the production broker, journal, inode
    # validation, lock and physical unlink, followed by observation.
    ctx.host.runner.advance()
    assert not rig.final.exists()
    assert rig.source.read_bytes() == source
    assert rig.journal.get("c" * 32).phase == "completed"
    assert rig.journal.get(rig.consent.operation_id) is None
    assert rig.storage.device_placement_get(
        rig.consent.device_id, rig.consent.artifact_id,
    )["observed_state"] == "missing"
    assert "Retrait USB supervisé terminé" in (
        ctx.host._reader_status_label.label
    )


@pytest.mark.parametrize("change", ["navigation", "source_revocation"])
def test_admitted_usb_removal_survives_navigation_not_real_revocation(
    gtk_core, change,
):
    ctx = gtk_core
    rig = ctx.rig
    before = rig.final.read_bytes()
    ctx.button.callbacks["clicked"](ctx.button)
    ctx.host.runner.advance()
    assert len(ctx.dialogs) == 1
    ctx.dialogs[0].answer("delete")
    assert len(ctx.host.runner.jobs) == 1

    # The destructive confirmation is already admitted. Navigation can
    # suppress UI feedback, but durable revocation must stop the unlink.
    ctx.host._reader_selection_generation += 1
    rig.service._account_context_epoch += 2
    if change == "source_revocation":
        rig.service._source_context_epoch = 1
    ctx.host.runner.advance()
    if change == "navigation":
        assert not rig.final.exists()
        assert rig.journal.get("c" * 32).phase == "completed"
    else:
        assert rig.final.read_bytes() == before
        assert rig.journal.get("c" * 32) is None
    assert "Retrait USB supervisé terminé" not in ctx.host._reader_status_label.label
    assert rig.source.read_bytes() == before
    assert rig.journal.get(rig.consent.operation_id) is None
