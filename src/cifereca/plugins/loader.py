from __future__ import annotations

import importlib
import importlib.machinery
import sys
from contextlib import contextmanager
from pathlib import Path
from typing import Iterator

from .errors import PluginActivationError


# Keep public module names stable for lazy imports, spawn and pickle.
# Reject overlapping ownership instead of path/order-dependent imports.
_SUFFIXES = tuple(sorted(importlib.machinery.all_suffixes(), key=len, reverse=True))
_RESERVED = frozenset(getattr(sys, "stdlib_module_names", ())) | {"cifereca"}


def _module_stem(path: Path) -> str | None:
    for suffix in _SUFFIXES:
        if path.name.endswith(suffix):
            name = path.name[:-len(suffix)]
            return name if name.isidentifier() and name != "__init__" else None
    return None


def package_import_names(root: Path) -> frozenset[str]:
    """Inventory Python-bearing top-level namespaces without importing code.

    A directory with Python code owns its top-level name even without an
    __init__.py (namespace packages). Data-only directories are not claims.
    Ignore generated bytecode caches, not shipped standalone modules.
    """
    names = set()
    for path in root.iterdir():
        if path.is_file():
            name = _module_stem(path)
            if name:
                names.add(name)
        elif path.is_dir() and path.name.isidentifier() and path.name != "__pycache__":
            if any(
                item.is_file()
                and "__pycache__" not in item.relative_to(path).parts
                and (item.name == "__init__.py" or _module_stem(item))
                for item in path.rglob("*")
            ):
                names.add(path.name)
    return frozenset(names)


def package_namespace_conflicts(
    roots: dict[str, Path],
) -> dict[str, tuple[str, ...]]:
    """Symmetric conflict result: no package wins by activation order."""
    claims: dict[str, set[str]] = {}
    failures: dict[str, set[str]] = {}
    for owner, root in sorted(roots.items()):
        try:
            for name in package_import_names(root):
                claims.setdefault(name, set()).add(owner)
        except OSError:
            failures.setdefault(owner, set()).add("inventory_unavailable")
    for name, owners in claims.items():
        if len(owners) > 1 or name in _RESERVED:
            for owner in owners:
                failures.setdefault(owner, set()).add(name)
    return {owner: tuple(sorted(names)) for owner, names in failures.items()}


def _within_package(module, root: Path) -> bool:
    """Namespace paths and regular module origin must belong to this root."""
    filename = getattr(module, "__file__", None)
    try:
        paths = [filename] if filename else list(getattr(module, "__path__", ()))
        return bool(paths) and all(
            (resolved := Path(path).resolve()) == root or root in resolved.parents
            for path in paths
        )
    except (TypeError, ValueError, OSError):
        return False


def assert_package_imports_available(root: Path) -> None:
    """Do not inherit already-loaded foreign helpers or evict their modules."""
    resolved = root.resolve()
    for name in package_import_names(resolved):
        if name in sys.modules and not _within_package(sys.modules[name], resolved):
            raise PluginActivationError("plugin import namespace already occupied")


@contextmanager
def package_import_path(root: Path) -> Iterator[None]:
    value = str(root)
    sys.path.insert(0, value)
    try:
        yield
    finally:
        try:
            sys.path.remove(value)
        except ValueError:
            pass


def load_entrypoint(root: Path, entrypoint: str) -> object:
    if ":" not in entrypoint:
        raise PluginActivationError(f"invalid plugin entrypoint: {entrypoint!r}")
    module_name, attr = (part.strip() for part in entrypoint.split(":", 1))
    if not module_name or not attr:
        raise PluginActivationError(f"invalid plugin entrypoint: {entrypoint!r}")
    try:
        # The manager retires old roots before activation. A live sibling
        # may intentionally share this module; never evict its classes
        # (or a foreign entrypoint) from the global import cache.
        assert_package_imports_available(root)
        with package_import_path(root):
            module = importlib.import_module(module_name)
            if not _within_package(module, root.resolve()):
                raise PluginActivationError("plugin entrypoint is outside its package")
            return getattr(module, attr)
    except Exception as exc:
        raise PluginActivationError(f"cannot load plugin entrypoint {entrypoint}: {exc}") from exc
