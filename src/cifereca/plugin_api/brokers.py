from __future__ import annotations

from typing import Any, Callable, Mapping, Protocol, runtime_checkable
from .models import (
    AccountRef, ActionStatistics, ArtifactFormat, ArtifactInputLease, ArtifactOutputLease, ArtifactRef, ArtifactRoutePlan,
    ArtifactRouteRequest, ArtifactRouteTarget, ArtifactTransferResult, ArtifactVariant, CacheNamespaceInfo, CachePurgeResult, CatalogSearchBatch, CatalogSearchSummary, LibraryMutationPlan,
    LibraryMutationRequest, LibraryMutationResult, LogicalBookArtifacts, SyncRequest, SyncResult, SyncSourceRef,
    TaskControl, TransformRequest, TransformResult,
)

@runtime_checkable
class CatalogBroker(Protocol):
    def search(self, query: str, **options: Any) -> list[Any]: ...
    def search_progressive(self, query: str, *, on_batch: Callable[[CatalogSearchBatch], None], control: TaskControl | None = None, **options: Any) -> CatalogSearchSummary: ...
    def holdings(self, item: Any, **options: Any) -> Any: ...
    def searchable_providers(self) -> list[tuple[str, str]]: ...
    def catalog_entries(self, **options: Any) -> list[Mapping[str, Any]]: ...

@runtime_checkable
class AcquisitionBroker(Protocol):
    def can_download(self, item: Any) -> bool: ...
    def eligible_accounts(self, item: Any, *, identity_id: str | None = None) -> tuple[AccountRef, ...]: ...
    def acquire(self, item: Any, *, identity_id: str | None = None, account_id: str | None = None) -> Any: ...
    def import_acsm(self, path: Any, **options: Any) -> Any: ...

@runtime_checkable
class SynchronizationBroker(Protocol):
    def sources(self, identity_id: str | None = None) -> tuple[SyncSourceRef, ...]: ...
    def set_enabled(self, source_id: str, enabled: bool) -> SyncSourceRef: ...
    def synchronize_source(self, source_id: str, request: SyncRequest | None = None, control: Any = None) -> SyncResult: ...
    def synchronize(self, request: SyncRequest, control: Any = None) -> SyncResult: ...
    def subscribe(self, callback: Any) -> Any: ...

@runtime_checkable
class MetadataBroker(Protocol):
    def library_entries(self, **options: Any) -> list[Mapping[str, Any]]: ...
    def scan(self, **options: Any) -> Mapping[str, Any]: ...

@runtime_checkable
class ReconciliationBroker(Protocol):
    def reconcile_acquisitions(self) -> Mapping[str, Any]: ...

@runtime_checkable
class IdentityBroker(Protocol):
    def identities(self) -> list[Mapping[str, Any]]: ...
    def select(self, identity_id: str) -> Any: ...
    def accounts(self, identity_id: str | None = None) -> tuple[AccountRef, ...]: ...
    def statistics(self, identity_id: str, *, window_seconds: int = 2592000) -> Mapping[str, Any]: ...

@runtime_checkable
class CacheBroker(Protocol):
    def namespaces(self) -> tuple[CacheNamespaceInfo, ...]: ...
    def purge(self, namespace_id: str = "", *, expired_only: bool = False) -> CachePurgeResult: ...

@runtime_checkable
class DiagnosticsBroker(Protocol):
    def snapshot(self) -> tuple[Mapping[str, Any], ...]: ...
    def system_status(self) -> Mapping[str, Any]: ...
    def export_text(self) -> str: ...

@runtime_checkable
class LibraryNamingBroker(Protocol):
    def preview(self, *, title: str, author: str = "", series: str = "", index: str = "", extension: str = "epub") -> str: ...

@runtime_checkable
class ArtifactExecutionBroker(Protocol):
    def input_lease(self, artifact: ArtifactRef) -> ArtifactInputLease: ...
    def output_lease(self, source: ArtifactRef, *, output_format: ArtifactFormat, proposed_filename: str = "", variant_kind: str = "") -> ArtifactOutputLease: ...
    def commit_variant(self, *, source: ArtifactRef, destination: ArtifactOutputLease, result: TransformResult, transformer_plugin_id: str, profile_plugin_id: str | None = None, options_fingerprint: str = "") -> ArtifactRef: ...
    def abort_output(self, destination: ArtifactOutputLease) -> None: ...
    def execute_transform(self, request: TransformRequest, *, transformer_plugin_id: str = "", control: TaskControl | None = None) -> ArtifactRef: ...
    def variants(self, source: ArtifactRef) -> tuple[ArtifactVariant, ...]: ...

@runtime_checkable
class LibraryReadBroker(Protocol):
    def book(self, book_id: str) -> LogicalBookArtifacts | None: ...
    def artifact(self, artifact_id: str) -> ArtifactRef | None: ...
    def for_artifact(self, artifact_id: str) -> LogicalBookArtifacts | None: ...
    def preferred_artifact(self, book_id: str, *, purpose: str = "read") -> ArtifactRef | None: ...

@runtime_checkable
class LibraryMaintenanceBroker(Protocol):
    def plan(self, request: LibraryMutationRequest) -> LibraryMutationPlan: ...
    def run(self, plan: LibraryMutationPlan, control: TaskControl | None = None) -> LibraryMutationResult: ...

@runtime_checkable
class ArtifactRoutingBroker(Protocol):
    def targets(self, request: ArtifactRouteRequest) -> tuple[ArtifactRouteTarget, ...]: ...
    def plan(self, request: ArtifactRouteRequest) -> ArtifactRoutePlan: ...
    def transfer(self, plan: ArtifactRoutePlan, control: TaskControl | None = None) -> ArtifactTransferResult: ...

__all__ = ["CatalogBroker", "AcquisitionBroker", "SynchronizationBroker", "MetadataBroker", "ReconciliationBroker", "IdentityBroker", "DiagnosticsBroker", "LibraryNamingBroker",
    "ArtifactExecutionBroker", "LibraryReadBroker", "LibraryMaintenanceBroker", "ArtifactRoutingBroker", "CacheBroker"]
